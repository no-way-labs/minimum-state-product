def anchor_for_case(
    regime_label: str,
    orientation: str,
    include_upper_wiggle: bool,
) -> StaticAnchor:
    return STATIC_BASE_ANCHORS[(regime_label, orientation, include_upper_wiggle)]


def generate_spine(n: int, anchor: StaticAnchor) -> frozenset[AnchoredRule]:
    if n < anchor.base_n:
        raise ValueError(f"n={n} is below base_n={anchor.base_n}")

    spine = anchor.base_spine
    for _ in range(anchor.base_n, n):
        spine = apply_template_step(spine, anchor.template_id)
    return spine


def expected_size(n: int, anchor: StaticAnchor) -> int:
    return len(generate_spine(n, anchor))


def print_summary() -> None:
    for key in sorted(STATIC_BASE_ANCHORS):
        anchor = STATIC_BASE_ANCHORS[key]
        print(
            f"case={key} template={anchor.template_id} base_n={anchor.base_n} "
            f"base_gaps={anchor.base_gaps} base_size={len(anchor.base_spine)}"
        )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--mode", choices=("summary",), default="summary")
    args = parser.parse_args()
    if args.mode == "summary":
        print_summary()


if __name__ == "__main__":
    main()
