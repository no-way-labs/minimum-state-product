all_tp_edges = set()

for s in range(324):
    c0, c1, c2, cN3, cN2, cN1 = decode6(s)

    # Position 0: TBot(cN1, c0, c1) -- no TP change
    out = TBotVal(cN1, c0, c1)
    if out != c0:
        t = encode6(out, c1, c2, cN3, cN2, cN1)
        all_tp_edges.add((s, t))

