def TMidVal(L,S,R): return TMidVal_table.get((L,S,R), 0)
def TBotVal(L,S,R): return TBotVal_table.get((L,S,R), 0)
def TLowVal(L,S,R): return TLowVal_table.get((L,S,R), 0)
def THighVal(L,S,R): return THighVal_table.get((L,S,R), 0)
def TTopVal(L,S,R): return TTopVal_table.get((L,S,R), 0)

def decode6(s):
    cN1 = s % 2; s //= 2
    cN2 = s % 3; s //= 3
    cN3 = s % 3; s //= 3
    c2 = s % 3; s //= 3
    c1 = s % 3; s //= 3
    c0 = s
    return (c0, c1, c2, cN3, cN2, cN1)

def encode6(c0, c1, c2, cN3, cN2, cN1):
    return ((((c0*3+c1)*3+c2)*3+cN3)*3+cN2)*2+cN1

# Compute ALL TP-preserving privileged boundary transitions (n=9)
